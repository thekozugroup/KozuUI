"""Validate Kozu palette tokens and export web, Apple, and Android colors."""

import argparse
import json
from pathlib import Path
import re


ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / "platforms/apple/KozuColors.xcassets"
ANDROID = ROOT / "platforms/android/res"
HUES = ("orange", "green", "blue", "gold", "violet", "rose")
RAMPS = (*HUES, "graphite")
GRADES = ("50", "100", "200", "300", "400", "500", "600", "700", "800", "900", "950")
CHART_ROLES = tuple(f"chart{hue.title()}" for hue in HUES)
ROLES = (
    "canvas", "surface", "subtle", "ink", "secondary", "action", "onAction",
    "tint", "focus", "notice", "success", "info", *CHART_ROLES,
)
SEEDS = {
    ("orange", "400"): "#FF9765",
    ("green", "300"): "#A7D5A4",
    ("blue", "300"): "#ABC1FF",
    ("graphite", "50"): "#FCFCFC",
}
GLASS_PAINT = {
    "light": {
        "frost-control": "rgb(252 252 252 / 42%)",
        "frost-card": "rgb(252 252 252 / 52%)",
        "frost-overlay": "rgb(252 252 252 / 70%)",
    },
    "dark": {
        "frost-control": "rgb(13 23 38 / 34%)",
        "frost-card": "rgb(13 23 38 / 44%)",
        "frost-overlay": "rgb(13 23 38 / 60%)",
    },
}
INFO = {"author": "kozu", "version": 1}


def rgb(hex_color):
    return tuple(int(hex_color[i:i + 2], 16) / 255 for i in (1, 3, 5))


def luminance(hex_color):
    channels = (v / 12.92 if v <= 0.04045 else ((v + 0.055) / 1.055) ** 2.4
                for v in rgb(hex_color))
    return sum(value * weight for value, weight in zip(channels, (0.2126, 0.7152, 0.0722)))


def named_map(value, keys, label):
    if not isinstance(value, dict) or value.keys() != set(keys):
        raise ValueError(f"{label} must contain exactly {', '.join(keys)}")
    return {key: value[key] for key in keys}


def hex_map(value, keys, label):
    colors = named_map(value, keys, label)
    for key, color in colors.items():
        if not isinstance(color, str) or not re.fullmatch(r"#[0-9A-F]{6}", color):
            raise ValueError(f"{label}.{key} must be an uppercase #RRGGBB color")
    return colors


def load_palette(tokens):
    palette = named_map(json.loads(tokens.read_text(encoding="utf-8"))["palette"],
                        ("ramps", "semantic"), "palette")
    ramps = named_map(palette["ramps"], RAMPS, "palette.ramps")
    for hue, ramp in ramps.items():
        ramps[hue] = hex_map(ramp, GRADES, f"palette.ramps.{hue}")
        levels = list(map(luminance, ramps[hue].values()))
        if any(a <= b for a, b in zip(levels, levels[1:])):
            raise ValueError(f"palette.ramps.{hue} must descend in relative luminance")
    for (hue, grade), color in SEEDS.items():
        if ramps[hue][grade] != color:
            raise ValueError(f"palette.ramps.{hue}.{grade} must be {color}")

    themes = named_map(palette["semantic"], ("light", "dark"), "palette.semantic")
    swatches = {"#FFFFFF", *(color for ramp in ramps.values() for color in ramp.values())}
    for theme, values in themes.items():
        colors = hex_map(values, ROLES, f"palette.semantic.{theme}")
        if not set(colors.values()) <= swatches:
            raise ValueError(f"palette.semantic.{theme} must use ramp colors or white")
        levels = {role: luminance(color) for role, color in colors.items()}
        surfaces = ("canvas", "surface", "subtle", "tint")
        text_roles = ("ink", "secondary", "notice", "success", "info")
        functional_roles = ("action", "focus", *CHART_ROLES)
        pairs = [(role, bg, 4.5) for role in text_roles for bg in surfaces]
        pairs += [(role, bg, 3) for role in functional_roles for bg in surfaces]
        pairs.append(("onAction", "action", 4.5))
        for foreground, background, minimum in pairs:
            low, high = sorted((levels[foreground], levels[background]))
            contrast = (high + 0.05) / (low + 0.05)
            if contrast < minimum:
                raise ValueError(f"{theme} {foreground} on {background}: "
                                 f"{contrast:.2f}:1 is below {minimum}:1")
        themes[theme] = colors
    if themes["light"]["surface"] != "#FFFFFF":
        raise ValueError("palette.semantic.light.surface must be #FFFFFF")
    return ramps, themes


def css_rule(selector, colors, scheme=None, indent=""):
    declarations = [f"color-scheme: {scheme};"] if scheme else []
    declarations.extend(f"--kz-{name}: {value};" for name, value in colors.items())
    lines = [f"{selector} {{", *(f"  {line}" for line in declarations), "}"]
    return "\n".join(indent + line for line in lines)


def android_xml(colors):
    entries = [f'    <color name="kz_{name.replace("-", "_")}">{value}</color>'
               for name, value in colors.items()]
    return "\n".join(['<?xml version="1.0" encoding="utf-8"?>',
                      "<!-- Generated by tools/export_colors.py. -->",
                      "<resources>", *entries, "</resources>", ""])


def apple_color(hex_color):
    components = {key: f"{value:.6f}" for key, value in
                  zip(("red", "green", "blue", "alpha"), (*rgb(hex_color), 1))}
    return {"idiom": "universal", "color": {"color-space": "srgb", "components": components}}


def exports(ramps, themes):
    primitives = {f"{hue}-{grade}": color
                  for hue, ramp in ramps.items() for grade, color in ramp.items()}
    light, dark = (
        {re.sub(r"([A-Z])", r"-\1", key).lower(): color for key, color in theme.items()}
        for theme in themes.values()
    )
    light_css = {**light, **GLASS_PAINT["light"]}
    dark_css = {**dark, **GLASS_PAINT["dark"]}
    css = "\n\n".join((
        "/* Generated by tools/export_colors.py. */",
        css_rule(":root", primitives),
        css_rule(':root, [data-theme="light"]', light_css, "light"),
        css_rule('[data-theme="dark"]', dark_css, "dark"),
        "@media (prefers-color-scheme: dark) {\n"
        + css_rule(":root:not([data-theme])", dark_css, "dark", "  ") + "\n}",
    )) + "\n"
    yield ROOT / "web/palette.css", css
    yield ANDROID / "values/kozu_colors.xml", android_xml({**primitives, **light})
    yield ANDROID / "values-night/kozu_colors.xml", android_xml(dark)
    yield CATALOG / "Contents.json", json.dumps({"info": INFO}, indent=2) + "\n"
    for name, value in {**primitives, **light}.items():
        asset_name = "Kz" + "".join(part.title() for part in name.split("-"))
        variants = [apple_color(value)]
        if name in dark:
            variants.append({
                "appearances": [{"appearance": "luminosity", "value": "dark"}],
                **apple_color(dark[name]),
            })
        data = {"colors": variants, "info": INFO}
        yield CATALOG / f"{asset_name}.colorset/Contents.json", json.dumps(data, indent=2) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--tokens", type=Path, default=ROOT / "Kozu.tokens.json")
    parser.add_argument("--check", action="store_true", help="Fail if an export is missing or stale")
    args = parser.parse_args()
    try:
        files = dict(exports(*load_palette(args.tokens)))
        stale = [path for path, data in files.items()
                 if not path.is_file() or path.read_bytes() != data.encode("utf-8")]
        unexpected = sorted(set(CATALOG.glob("Kz*.colorset")) - {path.parent for path in files})
        if unexpected or (args.check and stale):
            parser.error("stale color exports:\n" + "\n".join(
                str(path.relative_to(ROOT)) for path in (*unexpected, *stale)))
        for path in stale:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(files[path].encode("utf-8"))
    except (KeyError, TypeError, ValueError, OSError) as error:
        parser.error(str(error))
    print(f"{'Verified' if args.check else 'Exported'} {len(files)} color files.")


if __name__ == "__main__":
    main()
